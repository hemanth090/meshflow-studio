#!/usr/bin/env node
/**
 * MeshFlow Studio build: concatenate the plain-JS module fragments into the single
 * `client.js` browser bundle consumed by the DSH module loader.
 *
 *   node build.mjs
 *
 * The bundle is a factory registration: running it only registers a lazy factory, whose body
 * materialises the plugin modules and returns the Client plugin `{ inject, apply }`.
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const srcDir = join(here, 'src');

const ORDER = [
  '00-prelude.js',
  '10-model.js',
  '20-engine.js',
  '25-exporter.js',
  '30-controls.js',
  '40-panels.js',
  '50-studio.js',
  '60-register.js',
];

const missing = ORDER.filter((name) => !existsSync(join(srcDir, name)));
if (missing.length) {
  console.error('meshflow-studio: missing module fragments: ' + missing.join(', '));
  process.exit(1);
}

const bodies = ORDER.map((name) => {
  const source = readFileSync(join(srcDir, name), 'utf8');
  if (/\b(?:^|\n)\s*(?:import|export)\b/.test(source)) {
    console.error('meshflow-studio: ' + name + ' uses ESM import/export; fragments must be plain scripts');
    process.exit(1);
  }
  return '/* ---- src/' + name + ' ---- */\n' + source.replace(/\s+$/, '') + '\n';
});

const banner = `/**
 * MeshFlow Studio - generated by build.mjs. Do not edit by hand.
 * Edit src/*.js and rebuild instead.
 */
`;

const bundle = `${banner}window.__ModuleLoader__.load({
  id: '@local/meshflow-studio',
  factory(require) {
    const React = require('react');
    const h = React.createElement;

${bodies.join('\n')}

    return MF.clientPlugin;
  },
});
`;

mkdirSync(here, { recursive: true });
writeFileSync(join(here, 'client.js'), bundle, 'utf8');

const lines = bundle.split('\n').length;
console.log('meshflow-studio: wrote client.js (' + lines + ' lines, ' + bundle.length + ' bytes)');
